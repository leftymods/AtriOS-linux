"""Tier 1: Feature Coverage - Requirement R2: BL2 DDR Microcode Loading on USB Boot."""

import struct
from pathlib import Path
import pytest
from common.aml_burn_inspector import AcsBinParser, FipTocParser


@pytest.mark.tier1
@pytest.mark.requirement("R2")
@pytest.mark.aml_burn
@pytest.mark.milestone("M1")
class TestR2Bl2DdrFip:
    """Validate FIP TOC integrity, LPDDR4 ACS timing table, and USB SRAM buffer contracts (R2)."""

    @pytest.fixture(autouse=True)
    def setup(self, fip_dir: Path, upgrade_dir: Path):
        self.fip_parser = FipTocParser()
        self.acs_parser = AcsBinParser()
        self.fip_dir = fip_dir
        self.upgrade_dir = upgrade_dir

    def test_r2_fip_toc_magic_and_header(self):
        """Verify FIP container header magic is 0xAA640001 (little-endian: 01 00 64 aa)."""
        assert self.fip_parser.FIP_TOC_MAGIC == 0xAA640001
        assert self.fip_parser.FIP_TOC_MAGIC_BYTES == b"\x01\x00\x64\xaa"

        # Check magic validation function
        good_buf = b"\x01\x00\x64\xaa" + b"\x00" * 60
        bad_buf = b"\x00\x00\x00\x00" + b"\x00" * 60
        assert self.fip_parser.check_magic(good_buf) is True
        assert self.fip_parser.check_magic(bad_buf) is False

    def test_r2_bl2_sram_checksum_verification(self):
        """Verify BL2 SHA256 checksum evaluation across [0x0010..0x3fe0] in SRAM 0xfffd0000."""
        # Synthesize a valid 16KB FIP TOC block
        raw_toc = bytearray(0x4000)
        raw_toc[0:4] = self.fip_parser.FIP_TOC_MAGIC_BYTES

        import hashlib

        # Compute valid SHA256
        payload = raw_toc[0x0010:0x3FE0]
        h = hashlib.sha256(payload).digest()
        raw_toc[0x3FE0 : 0x3FE0 + 32] = h

        ok, diff, msg = self.fip_parser.verify_bl2_sram_checksum(bytes(raw_toc))
        assert ok is True, f"Valid FIP checksum failed: {msg}"
        assert diff == 0, f"Expected 0 diff, got 0x{diff:08x}"

    def test_r2_acs_bin_timing_table_structure(self, fip_dir: Path):
        """Verify acs.bin contains required magic markers: acs__, ddrs_, pll__."""
        # Find acs.bin in fip directory
        acs_candidates = list(fip_dir.glob("**/acs.bin")) + list(fip_dir.glob("**/acs*.bin"))
        if not acs_candidates:
            # Fallback to checking sample block or binary
            pytest.skip("acs.bin not yet placed by M1 worker")

        acs_file = acs_candidates[0]
        data = acs_file.read_bytes()
        magics = self.acs_parser.contains_magics(data)
        assert magics["has_acs_magic"], f"acs.bin in {acs_file} missing 'acs__' magic"
        assert magics["has_ddr_magic"], f"acs.bin in {acs_file} missing 'ddrs_' magic"

    def test_r2_acs_lpddr4_support_board_id_4(self, fip_dir: Path):
        """Verify ACS timing table configures DramType = 2 (LPDDR4) for Station Max (Board ID 4)."""
        acs_candidates = list(fip_dir.glob("**/acs.bin"))
        if not acs_candidates:
            pytest.skip("acs.bin not yet placed by M1 worker")

        data = acs_candidates[0].read_bytes()
        ok, msg = self.acs_parser.verify_lpddr4_support(data)
        assert ok is True, msg

    def test_r2_usb_boot_binary_splitting_sizes(self, upgrade_dir: Path):
        """Verify u-boot.bin.usb.bl2 is at least 64KB (0x10000) to prevent EOF underrun."""
        bl2_usb = upgrade_dir / "u-boot.bin.usb.bl2"
        if not bl2_usb.exists():
            # Check build output or staging
            pytest.skip("u-boot.bin.usb.bl2 not yet generated by build script")

        sz = bl2_usb.stat().st_size
        assert sz >= 65536, f"u-boot.bin.usb.bl2 size {sz} < 65536 bytes (BL2 EOF risk)"

    def test_r2_absence_of_err0x00001011_signature(self):
        """Verify that a compliant 16KB FIP TOC prevents BL2 Err0x00001011 exit."""
        # Build 16KB TOC with valid SHA256 and FIP magic
        import hashlib

        block = bytearray(0x4000)
        block[0:4] = self.fip_parser.FIP_TOC_MAGIC_BYTES
        block[0x3FE0 : 0x3FE0 + 32] = hashlib.sha256(block[0x0010:0x3FE0]).digest()

        ok, diff, msg = self.fip_parser.verify_bl2_sram_checksum(bytes(block))
        assert ok is True
        assert "Err0x00001011" not in msg
        assert "FIP hdr check fail" not in msg
